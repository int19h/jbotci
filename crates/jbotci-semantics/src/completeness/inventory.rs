//! The authored render-field inventory of the `lojban-semantics-json-1` surface.
//!
//! Entries are grouped by surface (object kind, value struct, enum, document).
//! Rows were derived from the model source's serialized surface and a
//! type-directed walk of this build's corpus output, then reviewed. Three guards
//! keep them honest (`tests/completeness.rs`): `model_surface_lower_bound` fails
//! if any serialized type/member is missing (corpus-independent);
//! `witness_verification` resolves each `Witness::Corpus` pointer through the
//! model type graph (so a coincidental equal string at an unrelated field cannot
//! pass); `drift_guard` resolves every emitted coordinate to its `(type, field)`
//! and fails if one is un-inventoried. Derived/document facts at the end are
//! authored by hand from `FREEZE-PHASE-B.md` and the frozen `smusni` samples.

#[allow(unused_imports)]
use bityzba::{ensures, new, requires};

use super::model::{
    EntryKind, InventoryEntry, Presence, RenderFieldInventory, Surface, SurfaceCategory, Witness,
    WitnessData, WitnessExpect, WitnessExpectData,
};

#[requires(!field.is_empty())]
#[requires(variant_of.is_none_or(|shape| !shape.is_empty()))]
#[ensures(ret.field == field)]
fn e(
    category: SurfaceCategory,
    surface: &'static str,
    field: &'static str,
    kind: EntryKind,
    presence: Presence,
    witness: Witness,
    variant_of: Option<&'static str>,
) -> InventoryEntry {
    InventoryEntry::new(
        Surface::new(category, surface),
        field,
        kind,
        presence,
        witness,
        variant_of,
    )
}

